    /// <summary>
    /// Nesting class for reasons of why parsing could fail. The type union for it
    /// is 
    /// </summary>
    public abstract record ReasonOfFailureWhileParsing
    {
        /// <summary>
        /// The error is an unclassified error returned by the
        /// ANTLR's parser.
        /// </summary>
        public sealed record Unknown(string Reason);


        /// <summary>
        /// This error is when the explicit parsing mode is enabled,
        /// but the input lacks an operator (which is normally inserted
        /// automatically with explicit parsing mode turned off). For
        /// example, "2x" would give this error.
        /// </summary>
        public sealed record MissingOperator(string Details);

        /// <summary>
        /// This is a bug of AngouriMath. Something that we definitely
        /// do not expect. More: <see cref="AngouriMath.Core.Exceptions.AngouriBugException"/>.
        /// Please, report to the main repository.
        /// </summary>
        public sealed record InternalError(string Details);
    }
    
    

    internal static class Parser
    {
        // Antlr parser spams errors into TextWriter provided, we inherit from it to handle lexer/parser errors as ParseExceptions
        private sealed class AngouriMathTextWriter : TextWriter
        {
            public override Encoding Encoding => Encoding.UTF8;
            public override void WriteLine(string? s) => errors.Add(new Unknown(s ?? throw new System.ArgumentNullException()));
            public readonly List<ReasonWhyParsingFailed> errors = new();
        }
        
        private static int? GetNextToken(IList<IToken> tokens, int currPos)
        {
            while (tokens[currPos].Channel != 0)
                if (++currPos >= tokens.Count)
                    return null;
            return currPos;
        }
        
        /// <summary>
        /// Replaces each superscript exponent, <c>x²</c> or <c>x⁻¹</c>, by the tokens of the
        /// power written out, <c>^ 2</c> or <c>^ - 1</c>, so that it binds exactly as that does:
        /// <c>2x²</c> is <c>2 * x ^ 2</c> and <c>-x²</c> is <c>-(x ^ 2)</c>. Done before the
        /// omitted tokens are inserted, and whatever the explicit-parsing setting, since a
        /// superscript is a written operator and not an omitted one.
        /// https://github.com/asc-community/AngouriMath/issues/1242
        /// </summary>
        private static void ExpandSuperscripts(IList<IToken> tokenList, AngouriMathLexer lexer)
        {
            for (var i = 0; i < tokenList.Count; i++)
            {
                if (tokenList[i] is not { Type: AngouriMathLexer.SUPERSCRIPT } superscript)
                    continue;
                var text = superscript.Text;
                var negative = text[0] == '⁻';
                var digits = new StringBuilder(text.Length);
                foreach (var glyph in negative ? text.Substring(1) : text)
                    digits.Append(glyph switch
                    {
                        '¹' => '1',
                        '²' => '2',
                        '³' => '3',
                        _ => (char)('0' + (glyph - '⁰')),
                    });
                var number = new CommonToken(AngouriMathLexer.NUMBER, digits.ToString())
                    { Line = superscript.Line, Column = superscript.Column };
                tokenList[i] = lexer.Power;
                if (negative)
                    tokenList.Insert(++i, lexer.Minus);
                tokenList.Insert(++i, number);
            }
        }

        /// <summary>
        /// A call of <c>beta</c> or <c>norm</c> with one argument, refused. Each was read as the product of
        /// a variable named for it with its argument: <c>norm([3, 4])</c> was <c>norm * [3, 4]</c>, which
        /// simplifies to <c>[3 * norm, 4 * norm]</c> with no error, and <c>beta(x)</c> was <c>beta * x</c>.
        /// The functions are the two-argument forms, B(a, b) and the p-norm. Refused here, before the
        /// grammar, which would otherwise report only a count; the name without a bracket, and with a
        /// space before one, is still a variable, as the other names refused by name are.
        /// https://github.com/asc-community/AngouriMath/issues/2182
        /// </summary>
        private static void RefuseOneArgumentCalls(IList<IToken> tokenList)
        {
            for (var i = 0; i < tokenList.Count; i++)
            {
                var call = tokenList[i];
                if (call.Channel != 0 || DisplayName(call) is not ("'beta('" or "'norm('") || HasASecondArgument(tokenList, i))
                    continue;
                throw new FunctionArgumentCountException(DisplayName(call) == "'norm('"
                    ? "norm(v, p) is the p-norm of a vector and takes two arguments: the length is norm(v, 2), which is abs(v). " +
                      "A one-argument norm(...) is refused rather than read as the product of a variable named norm " +
                      "with its argument; write norm * (...) for that"
                    : "beta(a, b) is the beta function and takes two arguments. A one-argument beta(...) is refused " +
                      "rather than read as the product of a variable named beta with its argument; write beta * (...) for that");
            }

            static string DisplayName(IToken token) => AngouriMathLexer.DefaultVocabulary.GetDisplayName(token.Type);

            // Whether a comma stands at the call's own depth before the bracket that closes it.
            static bool HasASecondArgument(IList<IToken> tokens, int call)
            {
                var depth = 0;
                for (var j = call + 1; j < tokens.Count; j++)
                {
                    if (tokens[j].Channel != 0)
                        continue;
                    switch (DisplayName(tokens[j]))
                    {
                        case "','" when depth == 0:
                            return true;
                        case "')'" or "']'" or "']T'" or "'}'" or "'|)'":
                            if (depth-- == 0)
                                return false;
                            break;
                        case var opens when opens is "'('" or "'['" or "'{'" or "'(|'" || opens.EndsWith("('"):
                            depth++;
                            break;
                    }
                }
                return false;
            }
        }

        /// <summary>
        /// This method inserts omitted tokens when no
        /// explicit-only parsing is enabled. Otherwise,
        /// it will throw an exception.
        /// </summary>
        private static Either<Unit, ReasonWhyParsingFailed> InsertOmittedTokensOrProvideDiagnostic(IList<IToken> tokenList, AngouriMathLexer lexer)
        {
            const string NUMBER = nameof(NUMBER);
            const string VARIABLE = nameof(VARIABLE);
            const string PARENTHESIS_OPEN = "'('";
            const string PARENTHESIS_CLOSE = "')'";
            const string FUNCTION_OPEN = "\x1"; // Fake display name for all function tokens e.g. "'sin('"
         
            if (GetNextToken(tokenList, 0) is not { } leftId)
                return new Unit();
            
            for (var rightId = leftId + 1; rightId < tokenList.Count; leftId = rightId++)
            {
                if (GetNextToken(tokenList, rightId) is not { } nextRightId)
                    return new Unit();
                rightId = nextRightId;
                if ((GetType(tokenList[leftId]), GetType(tokenList[rightId])) switch
                    {
                        // A bracket that opens on `mod` is a congruence's modulus, `a = b (mod n)`,
                        // not a factor: `b (mod n)` is not `b * (mod n)`, which is nothing.
                        // https://github.com/asc-community/AngouriMath/issues/1409
                        (_, PARENTHESIS_OPEN) when OpensOnMod(tokenList, rightId) => null,
                        // 2x -> 2 * x       2sqrt -> 2 * sqrt       2( -> 2 * (
                        // x y -> x * y      x sqrt -> x * sqrt      x( -> x * (
                        // )x -> ) * x       )sqrt -> ) * sqrt       )( -> ) * (
                        (NUMBER or VARIABLE or PARENTHESIS_CLOSE, VARIABLE or FUNCTION_OPEN or PARENTHESIS_OPEN)
                            => lexer.Multiply,
                        // 3 2 -> 3 ^ 2      x2 -> x ^ 2             )2 -> ) ^ 2
                        (NUMBER or VARIABLE or PARENTHESIS_CLOSE, NUMBER) => lexer.Power,

                        _ => null
                    } is { } insertToken)
                    {
                        if (!MathS.Settings.ExplicitParsingOnly)
                            // Insert at j because we need to keep the first one behind
                            tokenList.Insert(rightId, insertToken);
                        else
                            return new ReasonWhyParsingFailed(new MissingOperator($"There should be an operator between {tokenList[leftId]} and {tokenList[rightId]}"));
                    }
            }
            
            return new Unit();
            
            static string GetType(IToken token) =>
                AngouriMathLexer.DefaultVocabulary.GetDisplayName(token.Type) is var type
                && type is not PARENTHESIS_OPEN && type.EndsWith("('") ? FUNCTION_OPEN : type;

            static bool OpensOnMod(IList<IToken> tokens, int parenthesis)
                => parenthesis + 1 < tokens.Count
                && GetNextToken(tokens, parenthesis + 1) is { } after
                && AngouriMathLexer.DefaultVocabulary.GetDisplayName(tokens[after].Type) == "'mod'";
        }
        
        internal static Either<Entity, Failure<ReasonWhyParsingFailed>> ParseSilent(string source)
        {
            var writer = new AngouriMathTextWriter();

            if (writer.errors.Count > 0)
                return new Failure<ReasonWhyParsingFailed>(writer.errors[0]);

            var lexer = new AngouriMathLexer(new AntlrInputStream(source), null, writer);
            var tokenStream = new CommonTokenStream(lexer);
            tokenStream.Fill();
            var tokenList = tokenStream.GetTokens();            

            if (tokenList.Count is 0)
                return new Failure<ReasonWhyParsingFailed>(
                    new ReasonWhyParsingFailed(
                        new InternalError(
                            $"{nameof(ParseException)} should have been thrown"
                        )
                    )
                );
            
            ExpandSuperscripts(tokenList, lexer);
            RefuseOneArgumentCalls(tokenList);
            if (InsertOmittedTokensOrProvideDiagnostic(tokenList, lexer).Is<ReasonWhyParsingFailed>(out var whyFailed))
                return new Failure<ReasonWhyParsingFailed>(whyFailed);

            
            var parser = new AngouriMathParser(tokenStream, null, writer);

            // First in SLL prediction, which never looks past the current rule for context:
            // it returns the tree LL would, or reports an error where the input needs LL's
            // context or is invalid, and it bails there rather than recovering, so either is
            // retried in LL below. LL's full-context prediction allocated 3.8 MB for one
            // twenty-token expression, and grew with every alternative `atom` has, so every
            // function added to the grammar cost every parse.
            parser.Interpreter.PredictionMode = PredictionMode.SLL;
            parser.ErrorHandler = new BailErrorStrategy();
            parser.RemoveErrorListeners();
            var read = false;
            try
            {
                parser.Parse();
                read = true;
            }
            // A syntax error, or an action that threw on an alternative SLL took and LL would
            // not have: neither is an answer, and LL gives the one there is.
            catch (Exception)
            {
                tokenStream.Seek(0);
                parser.Reset();
                parser.Interpreter.PredictionMode = PredictionMode.LL;
                parser.ErrorHandler = new DefaultErrorStrategy();
                parser.AddErrorListener(ConsoleErrorListener<IToken>.Instance);
            }

            // ANTLR reports a syntax error to the listener and then *recovers*, carrying on
            // with a rule context whose value was never assigned. The grammar's actions run
            // anyway and dereference it, so an invalid input can bring the parse down before
            // the error already sitting in `writer.errors` is ever read. Reading it is the
            // honest answer: the input really was invalid, and that is what the caller is
            // owed -- an exception under AngouriMathBaseException, as Docs/Usage/Exceptions.md
            // promises, rather than whatever the half-built tree happened to throw.
            //
            // Guarded on an error having been reported, so this cannot swallow a genuine bug:
            // where the parser throws with nothing recorded against the input, the exception
            // is ours and it keeps propagating.
            // https://github.com/asc-community/AngouriMath/issues/813
            if (!read)
                try
                {
                    parser.Parse();
                }
                catch (Exception) when (writer.errors.Count > 0)
                {
                    return new Failure<ReasonWhyParsingFailed>(writer.errors[0]);
                }

            if (writer.errors.Count > 0)
                return new Failure<ReasonWhyParsingFailed>(writer.errors[0]);

            return RationalLiterals(parser.Result);
        }

        /// <summary>
        /// Rewrites a quotient of two integer literals into the <see cref="Rational"/> it denotes,
        /// so that a <see cref="Rational"/>'s printed form parses back to a
        /// <see cref="Rational"/>.
        /// </summary>
        /// <remarks>
        /// <para>
        /// The rewrite itself is <see cref="Antlr.ParsingHelpers.RationalLiteral"/>, which the
        /// <c>domain(...)</c> rule also calls — on its argument, before annotating it. That is what
        /// lets this sweep hand back a bare <see cref="Rational"/> and read no codomain at all: a
        /// quotient reaching here has never been annotated, because the only syntax that annotates
        /// anything has already folded what it was given.
        /// </para>
        /// <para>
        /// Reading one would be wrong as well as unnecessary. An unannotated quotient carries the
        /// default, <see cref="Domain.Complex"/>, and a rational literal the tighter
        /// <see cref="Domain.Rational"/>, so copying it across would make <c>7/2</c> and <c>3.5</c>
        /// structurally unequal — the round trip this exists to fix, broken from the other end.
        /// Telling that default apart from a <c>domain(x, CC)</c> somebody wrote is what no reader
        /// of a finished tree can do, and it cost <c>domain(1/2, CC)</c> its annotation until
        /// the fold moved to where the annotation is applied.
        /// https://github.com/asc-community/AngouriMath/issues/1048
        /// </para>
        /// </remarks>
        private static Entity RationalLiterals(Entity parsed)
            => parsed.Replace(static node => Antlr.ParsingHelpers.RationalLiteral(node));

        internal static Entity Parse(string source)
            => ParseSilent(source)
                .Switch(
                    valid => valid,
                    // ANTLR's diagnostic is a line and a column and nothing else, which names
                    // no input once the string has travelled through a caller's own layers. The
                    // source is appended rather than prepended because the location is what the
                    // message is read for first, and because callers assert on that prefix.
                    failure => failure.Reason.Switch<Entity>(
                            unknown => throw new UnhandledParseException($"{unknown.Reason}, while parsing `{source}`"),
                            missingOperator => throw new MissingOperatorParseException($"{missingOperator.Details}, while parsing `{source}`"),
                            internalError => throw new AngouriBugException($"{internalError.Details}, while parsing `{source}`")
                    )
                );
    }
